-- Tabelas na base de dados (4..7)

-- Estados operacionais por elemento gerido (3..5)
CREATE TABLE estados (
	id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	estado VARCHAR(15) CHECK (estado IN ('disponível', 'alugada', 'em manutenção'))
);

-- Tipos de elemento gerido (1..2)
CREATE TABLE bicicletas (
	-- Identificador único
	id INT PRIMARY KEY UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	-- Atributos por elemento gerido (4..8)
	velocidade VARCHAR(10),
	autonomia VARCHAR(5),
	estado INT REFERENCES estados,
	estado_administrativo VARCHAR(15) CHECK (estado_administrativo IN ('aprovado', 'não aprovado')),
	peso VARCHAR(5)
);

-- tabela de histórico das operações
CREATE TABLE historico_operacao (
	id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	ts TIMESTAMP,
	username VARCHAR(16) REFERENCES utilizadores,
	bicicleta INT REFERENCES bicicletas,
	operacao VARCHAR(15) CHECK (operacao IN ('aluguer', 'avaria em stock', 'devolução', 'avaria em uso', 'conserto'))
);

-- tabela das alterações de estado
CREATE TABLE historico_estado (
	id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	ts TIMESTAMP,
	bicicleta INT REFERENCES bicicletas,
	estado_inicial INT REFERENCES estados,
	estado_final INT REFERENCES estados
);

CREATE TABLE utilizadores (
	username VARCHAR(16) PRIMARY KEY
);
